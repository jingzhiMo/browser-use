function createTempDir(prefix: string): { name: string; removeCallback: () => void } {
	const os = require('os');
	const path = require('path');
	const fs = require('fs');
	const tempDir = path.join(os.tmpdir(), `${prefix}${Math.random().toString(36).substring(2, 15)}`);
	fs.mkdirSync(tempDir, { recursive: true });
	return {
		name: tempDir,
		removeCallback: () => {
			try {
				fs.rmSync(tempDir, { recursive: true, force: true });
			} catch {
				// Ignore errors
			}
		},
	};
}
