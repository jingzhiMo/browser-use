// Helper function
function _get_enable_default_extensions_default(): boolean {
	/**Get the default value for enable_default_extensions from env var or True.*/
	const env_val = process.env.BROWSER_USE_DISABLE_EXTENSIONS;
	if (env_val !== undefined) {
		// If DISABLE_EXTENSIONS is truthy, return False (extensions disabled)
		return !['0', 'false', 'no', 'off', ''].includes(env_val.toLowerCase());
	}
	return true;
}

