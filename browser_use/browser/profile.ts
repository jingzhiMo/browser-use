export function get_window_adjustments(): [number, number] {
	/**Returns recommended x, y offsets for window positioning*/
	const platform = os.platform();
	if (platform === 'darwin') {
		// macOS
		return [-4, 24]; // macOS has a small title bar, no border
	} else if (platform === 'win32') {
		// Windows
		return [-8, 0]; // Windows has a border on the left
	} else {
		// Linux
		return [0, 0];
	}
}

export function validate_url(url: string, schemes: string[] = []): string {
	/**Validate URL format and optionally check for specific schemes.*/
	try {
		const parsed_url = new URL(url);
		if (!parsed_url.hostname) {
			throw new Error(`Invalid URL format: ${url}`);
		}
		if (schemes.length > 0 && parsed_url.protocol && !schemes.includes(parsed_url.protocol.slice(0, -1))) {
			throw new Error(`URL has invalid scheme: ${url} (expected one of ${schemes.join(', ')})`);
		}
		return url;
	} catch (error: any) {
		if (error instanceof TypeError) {
			throw new Error(`Invalid URL format: ${url}`);
		}
		throw error;
	}
}

export function validate_float_range(value: number, min_val: number, max_val: number): number {
	/**Validate that float is within specified range.*/
	if (!(min_val <= value && value <= max_val)) {
		throw new Error(`Value ${value} outside of range ${min_val}-${max_val}`);
	}
	return value;
}

export function validate_cli_arg(arg: string): string {
	/**Validate that arg is a valid CLI argument.*/
	if (!arg.startsWith('--')) {
		throw new Error(
			`Invalid CLI argument: ${arg} (should start with --, e.g. --some-key="some value here")`
		);
	}
	return arg;
}

