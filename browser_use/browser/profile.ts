	detect_display_configuration(): void {
		/**
		 * Detect the system display size and initialize the display-related config defaults:
		 *         screen, window_size, window_position, viewport, no_viewport, device_scale_factor
		 */
		const display_size = get_display_size();
		const has_screen_available = display_size !== null;
		this.screen = this.screen || display_size || { width: 1920, height: 1080 };

		// if no headless preference specified, prefer headful if there is a display available
		if (this.headless === null || this.headless === undefined) {
			this.headless = !has_screen_available;
		}

		// Determine viewport behavior based on mode and user preferences
		const user_provided_viewport = this.viewport !== null && this.viewport !== undefined;

		if (this.headless) {
			// Headless mode: always use viewport for content size control
			this.viewport = this.viewport || this.window_size || this.screen;
			this.window_position = undefined;
			this.window_size = undefined;
			this.no_viewport = false;
		} else {
			// Headful mode: respect user's viewport preference
			this.window_size = this.window_size || this.screen;

			if (user_provided_viewport) {
				// User explicitly set viewport - enable viewport mode
				this.no_viewport = false;
			} else {
				// Default headful: content fits to window (no viewport)
				this.no_viewport = this.no_viewport === null || this.no_viewport === undefined ? true : this.no_viewport;
			}
		}

		// Handle special requirements (device_scale_factor forces viewport mode)
		if (this.device_scale_factor && (this.no_viewport === null || this.no_viewport === undefined)) {
			this.no_viewport = false;
		}

		// Finalize configuration
		if (this.no_viewport) {
			// No viewport mode: content adapts to window
			this.viewport = undefined;
			this.device_scale_factor = undefined;
			this.screen = undefined;
		} else {
			// Viewport mode: ensure viewport is set
			this.viewport = this.viewport || this.screen;
			this.device_scale_factor = this.device_scale_factor || 1.0;
		}

		if (this.headless && this.no_viewport) {
			throw new Error('headless=True and no_viewport=True cannot both be set at the same time');
		}
	}

	static args_as_dict(args: string[]): Record<string, string> {
		/**Return the extra launch CLI args as a dictionary.*/
		const args_dict: Record<string, string> = {};
		for (const arg of args) {
			const parts = arg.split('=', 2);
			const key = parts[0].trim().replace(/^--/, '');
			const value = parts.length > 1 ? parts[1].trim() : '';
			args_dict[key] = value;
		}
		return args_dict;
	}

	static args_as_list(args: Record<string, string>): string[] {
		/**Return the extra launch CLI args as a list of strings.*/
		return Object.entries(args).map(([key, value]) => {
			const clean_key = key.replace(/^--/, '');
			return value ? `--${clean_key}=${value}` : `--${clean_key}`;
		});
	}
